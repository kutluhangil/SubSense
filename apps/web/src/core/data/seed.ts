import type { Subscription } from '../types';
import { isoInDays, clampedISO, parseDate } from '../lib/format';

/** Next future occurrence of a day-of-month, as ISO YYYY-MM-DD (month-end safe). */
function nextOccurrence(day: number): string {
  const now = new Date();
  const startOfToday = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  const thisMonth = clampedISO(now.getFullYear(), now.getMonth(), day);
  if ((parseDate(thisMonth)?.getTime() ?? 0) >= startOfToday.getTime()) return thisMonth;
  return clampedISO(now.getFullYear(), now.getMonth() + 1, day);
}

